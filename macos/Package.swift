// swift-tools-version: 6.2
// The SwiftUI app. Build it with `scripts/build-macos.sh`, which first builds the Rust core
// (crates/toolbox-ffi) into Rust/lib and generates the bindings in Sources/ToolboxBindings
// and Sources/toolbox_ffiFFI/include. `swift build` on its own works once those exist.

import PackageDescription

let rustLib = Context.packageDirectory + "/Rust/lib"

let package = Package(
    name: "Toolbox",
    platforms: [.macOS(.v14)],
    targets: [
        .executableTarget(
            name: "Toolbox",
            dependencies: ["ToolboxBindings"],
            swiftSettings: [.defaultIsolation(MainActor.self)]
        ),
        // Generated by uniffi-bindgen from crates/toolbox-ffi.
        .target(
            name: "ToolboxBindings",
            dependencies: ["toolbox_ffiFFI"],
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // The C header of the Rust static library, plus the library itself.
        .target(
            name: "toolbox_ffiFFI",
            linkerSettings: [
                .unsafeFlags(["-L", rustLib]),
                .linkedLibrary("toolbox_ffi"),
            ]
        ),
    ]
)
